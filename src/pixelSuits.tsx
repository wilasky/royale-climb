const GRIDS: Record<Suit, Grid> = {
  spades: SPADE,
  hearts: HEART,
  diamonds: DIAMOND,
  clubs: CLUB,
};

type Palette = {
  outline: string;
  shadow: string;
  ditherShadow: string;
  base: string;
  ditherBase: string;
  glow: string;
  ring: string;
};

const PAL_BLACK: Palette = {
  outline: "#04121a",
  shadow: "#0c3948",
  ditherShadow: "#134a5d",
  base: "#29b6d8",
  ditherBase: "#3fcdef",
  glow: "#eafcff",
  ring: "#00e5ff",
};
const PAL_RED: Palette = {
  outline: "#2b0416",
  shadow: "#7a2048",
  ditherShadow: "#8f2652",
  base: "#ff5fa8",
  ditherBase: "#ff7bb8",
  glow: "#ffe6f4",
  ring: "#ff2ea1",
};

export const SUIT_RING: Record<Suit, string> = {
  spades: PAL_BLACK.ring,
  clubs: PAL_BLACK.ring,
  hearts: PAL_RED.ring,
  diamonds: PAL_RED.ring,
};

export function PixelSuitGlow({
  suit,
  px,
  glow = true,
}: {
  suit: Suit;
  px: number;
  glow?: boolean;
}) {
  const grid = GRIDS[suit];
  const pal = suit === "hearts" || suit === "diamonds" ? PAL_RED : PAL_BLACK;
  const w = grid[0].length * px;
  const h = grid.length * px;
  return (
    <div
      style={{
        position: "relative",
        width: w,
        height: h,
        filter: glow ? `drop-shadow(0 0 ${px * 1.3}px ${pal.ring})` : undefined,
      }}
    >
      {grid.flatMap((row, y) =>
        row.map((cell, x) => {
          if (!cell) return null;
          let hex: string;
          if (cell === 1) hex = pal.outline;
          else if (cell === 2) hex = (x + y) % 2 === 0 ? pal.ditherShadow : pal.shadow;
          else if (cell === 3) hex = (x + y) % 2 === 0 ? pal.ditherBase : pal.base;
          else hex = pal.glow;
          return (
            <div
              key={`${x}-${y}`}
              style={{
                position: "absolute",
                left: x * px,
                top: y * px,
                width: px + 0.6,
                height: px + 0.6,
                background: hex,
              }}
            />
          );
        })
      )}
    </div>
  );
}
